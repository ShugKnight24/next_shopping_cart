/** Templates for a mode, already grouped for the picker's category headings. */
export const templateGroups = (mode) => {
  const groups = [];

  (TEMPLATES_BY_MODE[mode] ?? []).forEach((template) => {
    const existing = groups.find((g) => g.category === template.category);
    if (existing) existing.templates.push(template);
    else groups.push({ category: template.category, templates: [template] });
  });

  return groups;
};

export const findTemplate = (mode, id) =>
  (TEMPLATES_BY_MODE[mode] ?? []).find((template) => template.id === id) ??
  null;

/** The template a fresh editor opens on. */
export const defaultTemplate = (mode) =>
  (TEMPLATES_BY_MODE[mode] ?? [])[0] ?? null;
