/**
 * The template library — the "bunch of templates" half of the workbench.
 *
 * A template is a starting composition: an artboard size, a set of substrate
 * option overrides (the product itself), and an ordered stack of layer specs.
 * `applyTemplate` in `layerModel.js` turns each spec into a real layer and
 * carries the shopper's already-typed words across by `slotRole`, so browsing
 * templates rearranges the design without destroying the writing.
 *
 * Layer spec fields are exactly the layer model's fields. `x`/`y` are the layer
 * CENTRE in artboard space, so a left-aligned block sitting on a 48px margin
 * has `x = 48 + width / 2` and `align: 'left'`.
 *
 * Substrate keys are the option ids the product studios already use:
 *   poster  — artStyle  cosmic | sunburst | retro | minimal | botanical | sunset
 *             paper     cotton | canvas | luster
 *             frame     oak | black | white | gold | none
 *             mat       none | white | offwhite | black
 *             orientation portrait | landscape
 *   apparel — garment   hoodie | tee | jacket | kicks
 *             color     navy | slate | cream | pine | crimson | amber | lavender
 *             accent    ecru | ink | gold | sky | rose | kelly
 *             placement chest | pocket | back
 *             finish    satin | chain | screen | puff
 *   book    — theme     space | magic | sneaker | dino
 *             edition   hardcover | deluxe | softcover
 *
 * Font family ids match the studios: sans | serif | display | cursive (the book
 * studio only offers sans | serif | cursive, so book templates stay off display).
 * Art ids are the stamps in `drawStamp`.
 */

