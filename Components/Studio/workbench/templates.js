/**
 * Small factories so a composition reads as a composition rather than as a wall
 * of repeated `type:` keys. They are plain object literals — no state, no
 * identity, nothing a caller can mutate by accident.
 *
 * Every non-text layer still carries a `slotRole` ('accent' for rules, panels
 * and small marks, 'image' for the focal artwork). Without one, `applyTemplate`
 * treats it as a layer the shopper added themselves and keeps it when they swap
 * template, so decorations from every template they browsed pile up.
 */
const slot = (slotRole, name, props) => ({
  type: 'text',
  slotRole,
  name,
  ...props,
});

const panel = (name, props) => ({
  type: 'shape',
  slotRole: 'accent',
  shape: 'rect',
  name,
  ...props,
});

const rule = (name, props) => ({
  type: 'shape',
  slotRole: 'accent',
  shape: 'rect',
  name,
  radius: 0,
  ...props,
});

const oval = (name, props) => ({
  type: 'shape',
  slotRole: 'accent',
  shape: 'ellipse',
  name,
  ...props,
});

/** The focal artwork of a composition. */
const art = (name, props) => ({
  type: 'art',
  slotRole: 'image',
  name,
  ...props,
});

/** Decorative artwork — confetti, a small seal, a scattered star. */
const mark = (name, props) => ({
  type: 'art',
  slotRole: 'accent',
  name,
  ...props,
});

